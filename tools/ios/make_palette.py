"""Writes the iPhone app's palette from Android's theme, so the two phones can't drift (Plan I2 Task 1).

    python3 -I tools/ios/make_palette.py           # writes ios/Granger/Sources/App/Palette.swift
    python3 -I tools/ios/make_palette.py --check   # exits 1 if Palette.swift isn't what GrangerTheme.kt makes

Reads FieldKit, FieldColors, NightColors, FieldExtras and NightExtras from app/src/main/kotlin/app/granger/theme/GrangerTheme.kt.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
KT = ROOT / "app/src/main/kotlin/app/granger/theme/GrangerTheme.kt"
OUT = ROOT / "ios/Granger/Sources/App/Palette.swift"


def block(src: str, start: str) -> str:
    i = src.index(start)
    depth, j = 0, src.index("(", i)
    for k in range(j, len(src)):
        depth += {"(": 1, ")": -1}.get(src[k], 0)
        if depth == 0:
            return src[j + 1:k]
    raise ValueError(start)


def main() -> int:
    src = KT.read_text()
    kit = dict(re.findall(r"val (\w+) = Color\(0x([0-9A-Fa-f]{8})\)", src[src.index("object FieldKit"):src.index("val FieldColors")]))

    def value(v: str) -> str:
        v = v.strip()
        m = re.fullmatch(r"Color\(0x([0-9A-Fa-f]{8})\)", v)
        if m:
            return m.group(1)
        m = re.fullmatch(r"FieldKit\.(\w+)", v)
        if m:
            return kit[m.group(1)]
        raise ValueError(v)

    def scheme(name: str) -> dict:
        body = block(src, f"val {name}")
        return {k: value(v) for k, v in re.findall(r"(\w+) = ([^,\n]+),", body)}

    def extras(name: str) -> dict:
        body = block(src, f"val {name} = GrangerExtras")
        out = {}
        for k, v in re.findall(r"(\w+) = (Color\(0x[0-9A-Fa-f]{8}\)|FieldKit\.\w+|true|false)", body):
            if k == "night":
                continue
            out[k] = value(v)
        return out

    field, night = scheme("FieldColors"), scheme("NightColors")
    fx, nx = extras("FieldExtras"), extras("NightExtras")
    keys = list(field)
    xkeys = list(fx)

    def hexcolor(argb: str) -> str:
        return f"Color(argb: 0x{argb.upper()})"

    lines = [
        "// Generated by tools/ios/make_palette.py from app/src/main/kotlin/app/granger/theme/GrangerTheme.kt. Don't edit.",
        "import SwiftUI",
        "",
        "/// Field (daylight) and Night: the same colours as Android's FieldColors and NightColors (Plan T1).",
        "struct Palette: Sendable {",
    ]
    lines += [f"    let {k}: Color" for k in keys + xkeys]
    lines += ["", "    static let field = Palette("]
    lines += [f"        {k}: {hexcolor(field[k])}," for k in keys] + [f"        {k}: {hexcolor(fx[k])}," for k in xkeys]
    lines[-1] = lines[-1].rstrip(",")
    lines += ["    )", "", "    static let night = Palette("]
    lines += [f"        {k}: {hexcolor(night[k])}," for k in keys] + [f"        {k}: {hexcolor(nx[k])}," for k in xkeys]
    lines[-1] = lines[-1].rstrip(",")
    lines += ["    )", "}", "", "extension Color {", "    /// An Android-style 0xAARRGGBB colour.", "    init(argb: UInt32) {",
              "        self.init(.sRGB, red: Double((argb >> 16) & 0xFF) / 255, green: Double((argb >> 8) & 0xFF) / 255,",
              "                  blue: Double(argb & 0xFF) / 255, opacity: Double((argb >> 24) & 0xFF) / 255)", "    }", "}", ""]
    text = "\n".join(lines)
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("Palette.swift matches GrangerTheme.kt" if ok else "Palette.swift is out of date: run tools/ios/make_palette.py")
        return 0 if ok else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"{OUT.relative_to(ROOT)}: {len(keys)} scheme colours, {len(xkeys)} extras")
    return 0


if __name__ == "__main__":
    sys.exit(main())
